//! The profile a repository declares for itself, so `doctor` checks what `new` generated.
//!
//! `new` writes a one-line HTML comment at the top of the generated `CONFORMANCE.md`
//! ([`marker_line`]); `doctor` reads it back ([`parse`]) when `--profile` is omitted. The marker
//! lives in `CONFORMANCE.md` rather than in a new dot-file because that file already is the
//! repository's per-profile conformance record, and it renders invisibly on GitHub.
//!
//! Repositories generated before the marker existed are recognised by the fixed sentence their
//! `CONFORMANCE.md` template carried, so the fix reaches them without regeneration.

use project_canon_core::Archetype;

/// The repo-relative file that carries the declaration.
pub(crate) const FILE: &str = "CONFORMANCE.md";

const MARKER_PREFIX: &str = "<!-- project-canon profile:";
const MARKER_SUFFIX: &str = "-->";

/// The legacy template (project-canon ≤ 0.9.4) named the profile in one fixed sentence, always
/// preceded by this generator line.
const LEGACY_GENERATOR: &str = "Generated by `project-canon new`.";
const LEGACY_PREFIX: &str = "skill for the `";
const LEGACY_SUFFIX: &str = "` profile.";

/// The marker line `new` writes as the first line of `CONFORMANCE.md`.
pub(crate) fn marker_line(profile: Archetype) -> String {
    format!("{MARKER_PREFIX} {} {MARKER_SUFFIX}", profile.slug())
}

/// Parse a `CONFORMANCE.md` body. `Ok(None)` means the file declares nothing; `Err` means it
/// carries a marker naming an unknown profile, which doctor reports rather than silently checking
/// the default profile.
pub(crate) fn parse(content: &str) -> Result<Option<Archetype>, String> {
    for line in content.lines() {
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix(MARKER_PREFIX) {
            let Some(value) = rest.strip_suffix(MARKER_SUFFIX) else {
                return Err(format!("malformed profile marker {trimmed:?} in {FILE}"));
            };
            let value = value.trim();
            return from_slug(value).map(Some).ok_or_else(|| {
                format!(
                    "{FILE} declares unknown profile {value:?} (expected one of {}); fix the marker or pass --profile",
                    valid_slugs()
                )
            });
        }
    }
    if content.contains(LEGACY_GENERATOR) {
        if let Some(start) = content.find(LEGACY_PREFIX) {
            let rest = &content[start + LEGACY_PREFIX.len()..];
            if let Some(end) = rest.find(LEGACY_SUFFIX) {
                return Ok(from_slug(&rest[..end]));
            }
        }
    }
    Ok(None)
}

fn from_slug(slug: &str) -> Option<Archetype> {
    Archetype::ALL.into_iter().find(|a| a.slug() == slug)
}

fn valid_slugs() -> String {
    Archetype::ALL
        .iter()
        .map(|a| a.slug())
        .collect::<Vec<_>>()
        .join("/")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn marker_round_trips_for_every_profile() {
        for profile in Archetype::ALL {
            let body = format!("{}\n# x — canon conformance TODO\n", marker_line(profile));
            assert_eq!(parse(&body).unwrap(), Some(profile));
        }
    }

    #[test]
    fn no_marker_declares_nothing() {
        assert_eq!(parse("# hand-written conformance notes\n").unwrap(), None);
        assert_eq!(parse("").unwrap(), None);
    }

    #[test]
    fn unknown_or_malformed_marker_is_an_error() {
        let err = parse("<!-- project-canon profile: webapp -->\n").unwrap_err();
        assert!(err.contains("webapp") && err.contains("--profile"), "{err}");
        assert!(parse("<!-- project-canon profile: service\n").is_err());
    }

    #[test]
    fn legacy_template_sentence_is_recognised() {
        let body =
            "# svc — canon conformance TODO\n\nGenerated by `project-canon new`. Each row is a \
resolved section of the AI-first CLI canon provided by the `/ai-first-cli-canon` skill for the \
`service` profile. Flip `todo` → `pass`.\n";
        assert_eq!(parse(body).unwrap(), Some(Archetype::Service));
        // Without the generator line the sentence is not trusted.
        let edited = body.replace(LEGACY_GENERATOR, "");
        assert_eq!(parse(&edited).unwrap(), None);
    }
}
